package a68j.rt;

import java.lang.invoke.MethodHandle;

/**
 * A procedure value made from a Java object of a functional interface
 * (docs/java-modules.md, section 1): the adapter (Object target, Object[]
 * args) -> Object, generated by the compiler for the interface and the
 * mode, converts the arguments, calls the method of the interface and
 * converts the result.
 */
public final class JavaFn extends Proc {
    public final Object target;
    private final MethodHandle adapter;

    JavaFn(Object target, MethodHandle adapter) {
        this.target = target;
        this.adapter = adapter;
    }

    @Override
    public Object call(Object[] args) {
        try {
            return (Object) adapter.invokeExact(target, args);
        } catch (RuntimeException | Error e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }
}
