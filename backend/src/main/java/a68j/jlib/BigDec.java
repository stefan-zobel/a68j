package a68j.jlib;

import a68j.rt.JavaObject;

import java.math.BigDecimal;
import java.math.BigInteger;
import java.math.MathContext;
import java.math.RoundingMode;
import java.util.function.Supplier;
import java.util.regex.Pattern;

/**
 * The Java side of the mode Bigdecimal of the Algol 68 module Bigdecimals
 * (backend/lib/bigdecimals.a68, generated by tools/gen_bignums.py): an
 * immutable decimal, a java.math.BigDecimal. Only static methods, as they
 * are called through formal holes (nest Java).
 *
 * <p>Every operation rounds its result to the current precision, a number
 * of significant decimal digits (70 at the start, as the long long real of
 * Algol 68 Genie), half away from zero (docs/bigdecimals.md). The
 * precision can be changed at any time; values keep their digits.
 *
 * <p>The methods exact... convert an operand of another mode without
 * rounding, for the mixed operators of the module: the operator rounds only
 * its result. The methods of... are the operator DEC, which rounds.
 *
 * <p>The conversions have distinct names: a Java object fits every
 * parameter of a reference type at the same cost, so of(String) and
 * of(BigInt) would make a formal hole ambiguous.
 */
public final class BigDec extends JavaObject {
    private static final int DEFAULT_PRECISION = 70;

    /** The current precision; read by every operation, set by setPrecision. */
    private static volatile MathContext context = new MathContext(DEFAULT_PRECISION, RoundingMode.HALF_UP);

    /** A decimal number of DEC s: a sign, digits with a point, an exponent. */
    private static final Pattern NUMBER = Pattern.compile("[+-]?([0-9]+(\\.[0-9]*)?|\\.[0-9]+)([eE][+-]?[0-9]+)?");

    private final BigDecimal v;

    private BigDec(BigDecimal v) {
        this.v = v;
    }

    @Override
    protected String javaClassName() {
        return "Bigdecimal";
    }

    private static BigDec make(BigDecimal v) {
        return new BigDec(v);
    }

    /** The value of B; NIL is a runtime error. */
    private static BigDecimal val(BigDec b) {
        if (b == null) {
            throw error("attempt to use a NIL Bigdecimal");
        }
        return b.v;
    }

    private static BigDecimal nonZero(BigDecimal d) {
        if (d.signum() == 0) {
            throw error("division by zero");
        }
        return d;
    }

    /**
     * The result of an operation; an exponent beyond the limits of
     * BigDecimal (an int scale) is a runtime error.
     */
    private static BigDec compute(Supplier<BigDecimal> op) {
        try {
            return make(op.get());
        } catch (ArithmeticException e) {
            throw error("Bigdecimal with an exponent beyond the limits");
        }
    }

    // ------------------------------------------------------------------
    // The precision.
    // ------------------------------------------------------------------

    /** bigdec_set_precision (digits): digits >= 1. */
    public static void setPrecision(int digits) {
        if (digits < 1) {
            throw error("bigdec_set_precision with " + digits + " digits, which is not at least 1");
        }
        context = new MathContext(digits, RoundingMode.HALF_UP);
    }

    /** bigdec_precision. */
    public static int precision() {
        return context.getPrecision();
    }

    // ------------------------------------------------------------------
    // Conversions.
    // ------------------------------------------------------------------

    public static BigDec exactLong(long x) {
        return make(BigDecimal.valueOf(x));
    }

    /** A real (32 bits) as its shortest decimal, so that 0.1 is 0.1. */
    public static BigDec exactFloat(float x) {
        if (Float.isNaN(x) || Float.isInfinite(x)) {
            throw error(Float.isNaN(x) ? "DEC of a NaN" : "DEC of an infinite real");
        }
        return make(new BigDecimal(Float.toString(x)));
    }

    /** A long real as its shortest decimal. */
    public static BigDec exactDouble(double x) {
        if (Double.isNaN(x) || Double.isInfinite(x)) {
            throw error(Double.isNaN(x) ? "DEC of a NaN" : "DEC of an infinite real");
        }
        return make(new BigDecimal(Double.toString(x)));
    }

    public static BigDec exactBigint(BigInt b) {
        return make(new BigDecimal(BigInt.value(b)));
    }

    public static BigDec ofLong(long x) {
        return plus(exactLong(x));
    }

    public static BigDec ofFloat(float x) {
        return plus(exactFloat(x));
    }

    public static BigDec ofDouble(double x) {
        return plus(exactDouble(x));
    }

    public static BigDec ofBigint(BigInt b) {
        return plus(exactBigint(b));
    }

    /**
     * DEC s: a sign, digits with or without a point, an exponent with e or
     * E; white space around them.
     */
    public static BigDec parse(String s) {
        int i = 0;
        int j = s.length();
        while (i < j && isWhite(s.charAt(i))) {
            i++;
        }
        while (j > i && isWhite(s.charAt(j - 1))) {
            j--;
        }
        String t = s.substring(i, j);
        if (NUMBER.matcher(t).matches()) {
            try {
                return make(new BigDecimal(t, context));
            } catch (NumberFormatException | ArithmeticException e) {
                // An exponent beyond the limits: as any other text that is not a number.
            }
        }
        throw error("DEC of \"" + s + "\", which is not a decimal number");
    }

    /** White space as in the module Texts: blank, tab, newline, carriage return, form feed, vertical tab. */
    private static boolean isWhite(char c) {
        return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == 11;
    }

    /** TOREAL a. */
    public static float toFloat(BigDec a) {
        float f = val(a).floatValue();
        if (Float.isInfinite(f)) {
            throw error("TOREAL of a Bigdecimal beyond the limits of real");
        }
        return f;
    }

    /** TOLONGREAL a. */
    public static double toDouble(BigDec a) {
        double d = val(a).doubleValue();
        if (Double.isInfinite(d)) {
            throw error("TOLONGREAL of a Bigdecimal beyond the limits of long real");
        }
        return d;
    }

    /** ROUND a: the nearest integer, half away from zero. */
    public static BigInt round(BigDec a) {
        return BigInt.wrap(val(a).setScale(0, RoundingMode.HALF_UP).toBigIntegerExact());
    }

    /** ENTIER a: the largest integer not greater than a. */
    public static BigInt entier(BigDec a) {
        return BigInt.wrap(val(a).setScale(0, RoundingMode.FLOOR).toBigIntegerExact());
    }

    // ------------------------------------------------------------------
    // Monadic operators.
    // ------------------------------------------------------------------

    /** + a: a rounded to the current precision. */
    public static BigDec plus(BigDec a) {
        BigDecimal x = val(a);
        MathContext mc = context;
        return compute(() -> x.plus(mc));
    }

    public static BigDec negate(BigDec a) {
        BigDecimal x = val(a);
        MathContext mc = context;
        return compute(() -> x.negate(mc));
    }

    public static BigDec abs(BigDec a) {
        BigDecimal x = val(a);
        MathContext mc = context;
        return compute(() -> x.abs(mc));
    }

    public static int sign(BigDec a) {
        return val(a).signum();
    }

    // ------------------------------------------------------------------
    // Dyadic operators.
    // ------------------------------------------------------------------

    public static BigDec add(BigDec a, BigDec b) {
        BigDecimal x = val(a);
        BigDecimal y = val(b);
        MathContext mc = context;
        return compute(() -> x.add(y, mc));
    }

    public static BigDec subtract(BigDec a, BigDec b) {
        BigDecimal x = val(a);
        BigDecimal y = val(b);
        MathContext mc = context;
        return compute(() -> x.subtract(y, mc));
    }

    public static BigDec multiply(BigDec a, BigDec b) {
        BigDecimal x = val(a);
        BigDecimal y = val(b);
        MathContext mc = context;
        return compute(() -> x.multiply(y, mc));
    }

    public static BigDec divide(BigDec a, BigDec b) {
        BigDecimal x = val(a);
        BigDecimal y = nonZero(val(b));
        MathContext mc = context;
        return compute(() -> x.divide(y, mc));
    }

    /** a / b for two Bigints. */
    public static BigDec divideBigints(BigInt a, BigInt b) {
        BigDecimal x = new BigDecimal(BigInt.value(a));
        BigDecimal y = nonZero(new BigDecimal(BigInt.value(b)));
        MathContext mc = context;
        return compute(() -> x.divide(y, mc));
    }

    /** The comparison of a and b by value (1.0 equals 1.00): -1, 0 or 1. */
    public static int compare(BigDec a, BigDec b) {
        return val(a).compareTo(val(b));
    }

    /** a ** e, also for a negative e; 0 ** 0 is 1. */
    public static BigDec pow(BigDec a, int e) {
        BigDecimal x = val(a);
        if (e < 0) {
            nonZero(x);
        }
        if (e < -999999999) {
            throw error("Bigdecimal ** with the exponent " + e + ", which is beyond the limits");
        }
        MathContext mc = context;
        return compute(() -> x.pow(e, mc));
    }

    // ------------------------------------------------------------------
    // Procedures.
    // ------------------------------------------------------------------

    public static BigDec sqrt(BigDec a) {
        BigDecimal x = val(a);
        if (x.signum() < 0) {
            throw error("bigdec_sqrt of a negative Bigdecimal");
        }
        MathContext mc = context;
        return compute(() -> x.sqrt(mc));
    }

    /** bigdec_text (a): plain notation, without trailing zeros. */
    public static String text(BigDec a) {
        BigDecimal x = val(a);
        return x.signum() == 0 ? "0" : x.stripTrailingZeros().toPlainString();
    }

    // ------------------------------------------------------------------
    // Output with the rules of whole, fixed and float of the prelude
    // (backend/lib/standard.a68, RR 10.3.2.1), computed exactly.
    // ------------------------------------------------------------------

    private static final char ERRORCHAR = '*';

    /** bigdec_whole (a, width): fixed (a, width, 0), as whole of a real. */
    public static String whole(BigDec a, int width) {
        return fixed(val(a), width, 0);
    }

    /** bigdec_fixed (a, width, after). */
    public static String fixed(BigDec a, int width, int after) {
        return fixed(val(a), width, after);
    }

    /** bigdec_float (a, width, after, exp). */
    public static String floating(BigDec a, int width, int after, int exp) {
        return floating(val(a), width, after, exp);
    }

    private static String errorchars(int width) {
        return String.valueOf(ERRORCHAR).repeat(Math.abs(width));
    }

    private static String fixed(BigDecimal x, int width, int after) {
        boolean negative = x.signum() < 0;
        int length = Math.abs(width) - (negative || width > 0 ? 1 : 0);
        if (!(after >= 0 && (length > after || width == 0))) {
            return errorchars(width);
        }
        BigDecimal y = x.abs();
        if (width == 0) {
            // The loop of the prelude, while y + .5 * .1 ** after >= 10 ** length,
            // counts the digits before the point of y rounded to after places.
            int before = digitsBefore(y.setScale(after, RoundingMode.HALF_UP));
            length = after == 0 ? Math.max(1, before) : before + after + 1;
        }
        String s = subfixed(y, length, after);
        if (s.indexOf(ERRORCHAR) < 0) {
            if (length > s.length() && (s.isEmpty() || s.charAt(0) == '.')) {
                s = "0" + s;
            }
            s = (negative ? "-" : width > 0 ? "+" : "") + s;
            if (width != 0) {
                s = " ".repeat(Math.max(0, Math.abs(width) - s.length())) + s;
            }
            return s;
        } else if (after > 0) {
            return fixed(x, width, after - 1);
        } else {
            return errorchars(width);
        }
    }

    /** The number of digits before the point of R >= 0, none if R < 1. */
    private static int digitsBefore(BigDecimal r) {
        BigInteger i = r.toBigInteger();
        return i.signum() == 0 ? 0 : i.toString().length();
    }

    /**
     * Y >= 0 rounded to after places: the digits before the point (none if
     * they are 0), a point and after digits if after > 0; width errorchars
     * if that is longer than width.
     */
    private static String subfixed(BigDecimal y, int width, int after) {
        BigDecimal r = y.setScale(after, RoundingMode.HALF_UP);
        String s = r.toPlainString();
        if (s.startsWith("0")) {
            s = s.substring(1);
        }
        return s.length() > width ? errorchars(width) : s;
    }

    private static String floating(BigDecimal x, int width, int after, int exp) {
        int before = Math.abs(width) - Math.abs(exp) - (after != 0 ? after + 1 : 0) - 2;
        if (Integer.signum(before) + Integer.signum(after) <= 0) {
            return errorchars(width);
        }
        // standardize: y * 10 ** p = ABS x with 10 ** (before - 1) <= y < 10 ** before,
        // then y rounded to after places stays below 10 ** before.
        BigDecimal y = x.abs();
        long p = 0;
        if (y.signum() != 0) {
            long q = (long) y.precision() - y.scale() - 1 - before + 1;
            y = y.scaleByPowerOfTen((int) -q);
            p = q;
        }
        BigDecimal g = BigDecimal.ONE.scaleByPowerOfTen(before);
        if (y.add(new BigDecimal(BigInteger.valueOf(5), after + 1)).compareTo(g) >= 0) {
            y = BigDecimal.ONE.scaleByPowerOfTen(before - 1);
            p += 1;
        }
        String s = fixed(x.signum() < 0 ? y.negate() : y, Integer.signum(width) * (Math.abs(width) - Math.abs(exp) - 1), after)
                + "e" + BigInt.whole(BigInt.wrap(BigInteger.valueOf(p)), exp);
        if (exp == 0 || s.indexOf(ERRORCHAR) >= 0) {
            return floating(x, width, after != 0 ? after - 1 : 0, exp > 0 ? exp + 1 : exp - 1);
        }
        return s;
    }
}
