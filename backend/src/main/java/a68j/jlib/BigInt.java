package a68j.jlib;

import a68j.rt.JavaObject;

import java.math.BigInteger;

/**
 * The Java side of the mode Bigint of the Algol 68 module Bigints
 * (backend/lib/bigints.a68, generated by tools/gen_bignums.py): an
 * immutable integer of any size, a java.math.BigInteger. Only static
 * methods, as they are called through formal holes (nest Java).
 *
 * <p>The operations have the meaning of the Algol 68 operators on int
 * (docs/bigints.md): % truncates toward zero, MOD yields a value from 0 to
 * ABS b - 1. Errors (a NIL Bigint, a division by zero, a negative exponent,
 * a value beyond the limits of int) are runtime errors at the position of
 * the program that used the operator.
 *
 * <p>Every operation with a second operand comes in three forms: with two
 * Bigints, and with a long (an int, long int or long long int of Algol 68)
 * as the right or the left operand, so that a mixed operator is a single
 * call.
 */
public final class BigInt extends JavaObject {
    private final BigInteger v;

    private BigInt(BigInteger v) {
        this.v = v;
    }

    @Override
    protected String javaClassName() {
        return "Bigint";
    }

    private static BigInt make(BigInteger v) {
        return new BigInt(v);
    }

    /** The value of B; NIL is a runtime error. */
    private static BigInteger val(BigInt b) {
        if (b == null) {
            throw error("attempt to use a NIL Bigint");
        }
        return b.v;
    }

    private static BigInteger nonZero(BigInteger d) {
        if (d.signum() == 0) {
            throw error("division by zero");
        }
        return d;
    }

    // ------------------------------------------------------------------
    // Conversions.
    // ------------------------------------------------------------------

    public static BigInt of(long x) {
        return make(BigInteger.valueOf(x));
    }

    /** BIG s: decimal digits, a sign + or - directly before them, white space around. */
    public static BigInt parse(String s) {
        BigInteger r = parse(s, 10);
        if (r == null) {
            throw error("BIG of \"" + s + "\", which is not an integer");
        }
        return make(r);
    }

    /** big_from_text (s, radix): as BIG, with the digits of the radix (2 to 36, letters in either case). */
    public static BigInt parseRadix(String s, int radix) {
        checkRadix(radix, "big_from_text");
        BigInteger r = parse(s, radix);
        if (r == null) {
            throw error("big_from_text of \"" + s + "\", which is not an integer in radix " + radix);
        }
        return make(r);
    }

    /** The integer in S, or null. Only ASCII digits and letters count as digits. */
    private static BigInteger parse(String s, int radix) {
        int i = 0;
        int j = s.length();
        while (i < j && isWhite(s.charAt(i))) {
            i++;
        }
        while (j > i && isWhite(s.charAt(j - 1))) {
            j--;
        }
        int start = i;
        if (i < j && (s.charAt(i) == '+' || s.charAt(i) == '-')) {
            i++;
        }
        if (i == j) {
            return null;
        }
        for (int k = i; k < j; k++) {
            char c = s.charAt(k);
            if (c >= 128 || Character.digit(c, radix) < 0) {
                return null;
            }
        }
        return new BigInteger(s.substring(start, j), radix);
    }

    /** White space as in the module Texts: blank, tab, newline, carriage return, form feed, vertical tab. */
    private static boolean isWhite(char c) {
        return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == 11;
    }

    private static void checkRadix(int radix, String what) {
        if (radix < 2 || radix > 36) {
            throw error(what + " with the radix " + radix + ", which is not from 2 to 36");
        }
    }

    /** TOINT b. */
    public static int toInt(BigInt b) {
        BigInteger x = val(b);
        if (x.bitLength() > 31) {
            throw error("TOINT of a Bigint beyond the limits of int");
        }
        return x.intValue();
    }

    /** TOLONGINT b. */
    public static long toLong(BigInt b) {
        BigInteger x = val(b);
        if (x.bitLength() > 63) {
            throw error("TOLONGINT of a Bigint beyond the limits of long int");
        }
        return x.longValue();
    }

    /**
     * big_whole (b, width), with the rules of whole for an int: width 0 gives
     * as many characters as needed, a sign only for a negative value; any
     * other width gives ABS width characters, filled with blanks on the
     * left, with a sign always for a positive width and only for a
     * negative value for a negative width. A width too small gives
     * ABS width characters "*".
     */
    public static String whole(BigInt b, int width) {
        BigInteger x = val(b);
        String digits = x.abs().toString();
        boolean negative = x.signum() < 0;
        int signs = negative || width > 0 ? 1 : 0;
        int required = signs + digits.length();
        int available = width == 0 ? required : Math.abs(width);
        StringBuilder sb = new StringBuilder(Math.max(available, 0));
        if (available < required) {
            sb.repeat('*', available);
        } else {
            sb.repeat(' ', available - required);
            if (signs > 0) {
                sb.append(negative ? '-' : '+');
            }
            sb.append(digits);
        }
        return sb.toString();
    }

    /** big_text (b, radix): the digits in the radix (2 to 36, small letters), with a sign - if negative. */
    public static String text(BigInt b, int radix) {
        checkRadix(radix, "big_text");
        return val(b).toString(radix);
    }

    // ------------------------------------------------------------------
    // Monadic operators.
    // ------------------------------------------------------------------

    public static BigInt negate(BigInt a) {
        return make(val(a).negate());
    }

    public static BigInt abs(BigInt a) {
        BigInteger x = val(a);
        return x.signum() < 0 ? make(x.negate()) : a;
    }

    public static int sign(BigInt a) {
        return val(a).signum();
    }

    public static boolean odd(BigInt a) {
        return val(a).testBit(0);
    }

    // ------------------------------------------------------------------
    // Dyadic operators.
    // ------------------------------------------------------------------

    public static BigInt add(BigInt a, BigInt b) {
        return make(val(a).add(val(b)));
    }

    public static BigInt add(BigInt a, long b) {
        return make(val(a).add(BigInteger.valueOf(b)));
    }

    public static BigInt add(long a, BigInt b) {
        return make(BigInteger.valueOf(a).add(val(b)));
    }

    public static BigInt subtract(BigInt a, BigInt b) {
        return make(val(a).subtract(val(b)));
    }

    public static BigInt subtract(BigInt a, long b) {
        return make(val(a).subtract(BigInteger.valueOf(b)));
    }

    public static BigInt subtract(long a, BigInt b) {
        return make(BigInteger.valueOf(a).subtract(val(b)));
    }

    public static BigInt multiply(BigInt a, BigInt b) {
        return make(val(a).multiply(val(b)));
    }

    public static BigInt multiply(BigInt a, long b) {
        return make(val(a).multiply(BigInteger.valueOf(b)));
    }

    public static BigInt multiply(long a, BigInt b) {
        return make(BigInteger.valueOf(a).multiply(val(b)));
    }

    /** a % b, a OVER b: the quotient truncated toward zero. */
    public static BigInt divide(BigInt a, BigInt b) {
        return make(val(a).divide(nonZero(val(b))));
    }

    public static BigInt divide(BigInt a, long b) {
        return make(val(a).divide(nonZero(BigInteger.valueOf(b))));
    }

    public static BigInt divide(long a, BigInt b) {
        return make(BigInteger.valueOf(a).divide(nonZero(val(b))));
    }

    /** a MOD b, a %* b: from 0 to ABS b - 1, as for int. */
    public static BigInt mod(BigInt a, BigInt b) {
        return make(val(a).mod(nonZero(val(b)).abs()));
    }

    public static BigInt mod(BigInt a, long b) {
        return make(val(a).mod(nonZero(BigInteger.valueOf(b)).abs()));
    }

    public static BigInt mod(long a, BigInt b) {
        return make(BigInteger.valueOf(a).mod(nonZero(val(b)).abs()));
    }

    /** The comparison of a and b: -1, 0 or 1. */
    public static int compare(BigInt a, BigInt b) {
        return val(a).compareTo(val(b));
    }

    public static int compare(BigInt a, long b) {
        return val(a).compareTo(BigInteger.valueOf(b));
    }

    public static int compare(long a, BigInt b) {
        return BigInteger.valueOf(a).compareTo(val(b));
    }

    /** a ** e for e >= 0; 0 ** 0 is 1. */
    public static BigInt pow(BigInt a, int e) {
        BigInteger x = val(a);
        if (e < 0) {
            throw error("Bigint ** with the negative exponent " + e);
        }
        return make(x.pow(e));
    }

    // ------------------------------------------------------------------
    // Procedures.
    // ------------------------------------------------------------------

    public static BigInt gcd(BigInt a, BigInt b) {
        return make(val(a).gcd(val(b)));
    }

    /** The largest integer whose square is at most a. */
    public static BigInt sqrt(BigInt a) {
        BigInteger x = val(a);
        if (x.signum() < 0) {
            throw error("big_sqrt of a negative Bigint");
        }
        return make(x.sqrt());
    }

    /** b ** e MOD m, for e >= 0 and m > 0. */
    public static BigInt modPow(BigInt b, BigInt e, BigInt m) {
        BigInteger x = val(b);
        BigInteger y = val(e);
        BigInteger z = val(m);
        if (y.signum() < 0) {
            throw error("big_mod_pow with a negative exponent");
        }
        if (z.signum() <= 0) {
            throw error("big_mod_pow with a modulus that is not positive");
        }
        return make(x.modPow(y, z));
    }

    /** Whether a is a prime, with an error probability below 2 ** -100. */
    public static boolean probablePrime(BigInt a) {
        return val(a).isProbablePrime(100);
    }
}
