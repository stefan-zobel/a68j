#!/usr/bin/env python3
"""List the Rosetta Code solutions that run successfully with ga68 and a68j.

Usage: rosetta_list.py --dir tests/rosetta [--rcd RosettaCodeData] [-o FILE]

Reads DIR/results.tsv (rosetta_report.py) and writes a Markdown list of the
solutions that ga68 compiles and runs to a normal end (exit status 0) and
whose run on the JVM gives the same result: status pass (identical output)
or approx (identical up to the rounding of floating-point numbers).  With
--rcd (a RosettaCodeData checkout) the task names link to the Rosetta Code
pages given in Task/<task>/00-META.yaml; otherwise the links are derived
from the task directory names.  DIR/passing.txt gets the bare names.
"""
import argparse, os, re, urllib.parse


def task_url(rcd, task):
    if rcd:
        meta = os.path.join(rcd, "Task", task, "00-META.yaml")
        if os.path.exists(meta):
            m = re.search(r"^from:\s*(\S+)", open(meta, encoding="utf-8").read(), re.M)
            if m:
                return m.group(1).replace("http://", "https://")
    return "https://rosettacode.org/wiki/" + task.replace("-", "_")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--rcd")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    rows = []
    with open(os.path.join(a.dir, "results.tsv"), encoding="utf-8") as f:
        next(f)
        for line in f:
            name, task, ga68, jvm, note = (line.rstrip("\n").split("\t") + [""] * 5)[:5]
            if ga68 == "exit 0" and (jvm == "pass" or jvm.startswith("approx")):
                rows.append((name, task, "identical" if jvm == "pass" else "same up to rounding"))
    rows.sort()
    same = sum(1 for r in rows if r[2] == "identical")
    out = [
        "# Rosetta Code solutions that run with ga68 and a68j",
        "",
        "Generated by `tools/rosetta_list.py` from `results.tsv`. Listed are the",
        "solutions that ga68 compiles and that end normally (exit status 0), and whose",
        "run on the JVM gives the same result: the same output and the same exit",
        "status (*identical*) or the same output up to the rounding of floating-point",
        "numbers (*same up to rounding*, see README).",
        "",
        "%d solutions, %d of them identical and %d the same up to rounding." % (len(rows), same, len(rows) - same),
        "",
        "| No. | Program | Rosetta Code task | Result |",
        "|---:|---|---|---|",
    ]
    for i, (name, task, res) in enumerate(rows, 1):
        url = task_url(a.rcd, task)
        title = urllib.parse.unquote(url.rsplit("/", 1)[1]).replace("_", " ").replace("|", "\\|")
        out.append("| %d | [%s](%s.a68) | [%s](%s) | %s |" % (i, name, name, title, url, res))
    text = "\n".join(out) + "\n"
    if a.out:
        open(a.out, "w", encoding="utf-8").write(text)
    else:
        print(text, end="")
    with open(os.path.join(a.dir, "passing.txt"), "w", encoding="utf-8") as f:
        f.write("".join(r[0] + "\n" for r in rows))
    print("%d solutions" % len(rows), file=__import__("sys").stderr)


if __name__ == "__main__":
    main()
