#!/usr/bin/env python3
"""List the Rosetta Code solutions that run successfully with ga68 and a68j.

Usage: rosetta_list.py --dir tests/rosetta [--rcd RosettaCodeData] [-o FILE]

Reads DIR/results.tsv (rosetta_report.py) and writes a Markdown list of the
solutions that ga68 compiles and runs to a normal end (exit status 0) and
whose run on the JVM gives the same result: status pass (identical output),
fixed (identical to the corrected result, where a68j does not reproduce a
defect of ga68) or approx (identical up to the rounding of floating-point
numbers).  The task names link to the Rosetta Code pages: with --rcd (a
RosettaCodeData checkout) as given in Task/<task>/00-META.yaml, else as
given in the header of the prepared program DIR/<name>.a68; only if neither
has one is the link derived from the task directory name.  DIR/passing.txt
gets the bare names.
"""
import argparse, os, re, urllib.parse


def task_url(rcd, task, prog):
    if rcd:
        meta = os.path.join(rcd, "Task", task, "00-META.yaml")
        if os.path.exists(meta):
            m = re.search(r"^from:\s*(\S+)", open(meta, encoding="utf-8").read(), re.M)
            if m:
                return m.group(1).replace("http://", "https://")
    # The header of the prepared program (tools/rosetta_prep.py) gives the
    # page of the solution.
    if os.path.exists(prog):
        with open(prog, encoding="utf-8") as f:
            for line in list(f)[:6]:
                m = re.search(r"(https://rosettacode\.org/wiki/[^#\s]+)", line)
                if m:
                    return m.group(1)
    return "https://rosettacode.org/wiki/" + task.replace("-", "_")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--rcd")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    rows = []
    with open(os.path.join(a.dir, "results.tsv"), encoding="utf-8") as f:
        next(f)
        for line in f:
            name, task, ga68, jvm, note = (line.rstrip("\n").split("\t") + [""] * 5)[:5]
            if ga68 == "exit 0" and (jvm == "pass" or jvm.startswith("fixed") or jvm.startswith("approx")):
                rows.append((name, task, "identical" if jvm == "pass"
                             else "identical (corrected)" if jvm.startswith("fixed")
                             else "same up to rounding"))
    rows.sort()
    same = sum(1 for r in rows if r[2] == "identical")
    corrected = sum(1 for r in rows if r[2] == "identical (corrected)")
    out = [
        "# Rosetta Code solutions that run with ga68 and a68j",
        "",
        "Generated by `tools/rosetta_list.py` from `results.tsv`. Listed are the",
        "solutions that ga68 compiles and that end normally (exit status 0), and whose",
        "run on the JVM gives the same result: the same output and the same exit",
        "status (*identical*), the same as the corrected result where a68j does not",
        "reproduce a defect of ga68 (*identical (corrected)*, see `fixed/`), or the",
        "same output up to the rounding of floating-point numbers (*same up to",
        "rounding*, see README).",
        "",
        "%d solutions: %d identical, %d identical to the corrected result and %d the same up to rounding."
        % (len(rows), same, corrected, len(rows) - same - corrected),
        "",
        "| No. | Program | Rosetta Code task | Result |",
        "|---:|---|---|---|",
    ]
    for i, (name, task, res) in enumerate(rows, 1):
        url = task_url(a.rcd, task, os.path.join(a.dir, name + ".a68"))
        title = urllib.parse.unquote(url.rsplit("/", 1)[1]).replace("_", " ").replace("|", "\\|")
        out.append("| %d | [%s](%s.a68) | [%s](%s) | %s |" % (i, name, name, title, url, res))
    text = "\n".join(out) + "\n"
    if a.out:
        open(a.out, "w", encoding="utf-8").write(text)
    else:
        print(text, end="")
    with open(os.path.join(a.dir, "passing.txt"), "w", encoding="utf-8") as f:
        f.write("".join(r[0] + "\n" for r in rows))
    print("%d solutions" % len(rows), file=__import__("sys").stderr)


if __name__ == "__main__":
    main()
