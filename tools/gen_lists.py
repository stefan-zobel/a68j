def java_class(mode, amode, cls, elem, rowtype, desc):
    if elem == "Row":
        return JAVA.format(
            mode=mode, cls=cls, elem=elem, rowtype=rowtype, desc=desc,
            imports="import a68j.rt.Row;\nimport a68j.rt.JavaConv;\n",
            storage=" and holds copies of the strings",
            of_array='''        int k = (int) r.size(0);
        {cls} l = new {cls}(k);
        for (int i = 0; i < k; i++) {{
            l.a[i] = JavaConv.element(r, i).copy();
        }}
        l.n = k;
        return l;'''.format(cls=cls),
            keep_x="x.copy()",
            give_a_i="l.a[i - 1].copy()",
            forget_last="        l.a[l.n] = null;",
            clear="        Arrays.fill(l.a, 0, l.n, null);",
            to_array='''        Object[] e = new Object[l.n];
        for (int i = 0; i < l.n; i++) {
            e[i] = l.a[i].copy();
        }
        return Row.of1(1, l.n, e);''',
            sort="        Arrays.sort(l.a, 0, l.n, JavaConv::compareStrings);",
            get_boxed="l.a[i - 1].copy()", set_unboxed="((Row) v).copy()",
            equal="JavaConv.compareStrings(l.a[i], x) == 0")
    return JAVA.format(
        mode=mode, cls=cls, elem=elem, rowtype=rowtype, desc=desc, imports="",
        storage=", but stores the values unboxed in a " + elem + "[]",
        of_array='''        {cls} l = new {cls}(r.length);
        System.arraycopy(r, 0, l.a, 0, r.length);
        l.n = r.length;
        return l;'''.format(cls=cls),
        keep_x="x", give_a_i="l.a[i - 1]", forget_last="", clear="",
        get_boxed="l.a[i - 1]", set_unboxed="(" + {"int": "Integer", "long": "Long", "float": "Float", "double": "Double", "boolean": "Boolean"}[elem] + ") v",
        to_array="        return Arrays.copyOf(l.a, l.n);",
        sort=('''        // FALSE before TRUE.
        int f = 0;
        for (int i = 0; i < l.n; i++) {
            if (!l.a[i]) {
                f++;
            }
        }
        Arrays.fill(l.a, 0, f, false);
        Arrays.fill(l.a, f, l.n, true);''' if elem == "boolean" else
              "        Arrays.sort(l.a, 0, l.n);"),
        equal="l.a[i] == x")


ALGOL_HEAD = '''{ dg-options "-fstropping=supper -fnest-java" }

{ lists.a68 - the module Lists of a68j.  Generated by tools/gen_lists.py;
  do not edit.

  Lists that grow like java.util.ArrayList, by appending at the end in
  amortised constant time (a FLEX row is copied as a whole whenever it
  grows), one mode per element mode:

      Intlist       int          Longintlist    long int
      Reallist      real         Longreallist   long real
      Boollist      bool         Stringlist     string

  The values are kept unboxed in a Java array (a68j.jlib.IntList ...); a
  Stringlist keeps copies of the strings.

  A list is a Java object: a name that refers to no Algol 68 value.  It can
  be passed around, compared with IS, ISNT and NIL and given to the
  operators and procedures below, but not dereferenced or assigned to.
  Indices go from 1 to UPB l.  For a list l of mode M with elements of
  mode E:

      new_m                    a new empty list, e.g. new_intlist
      new_m_with_capacity (n)  the same with room for n elements
      m_of (r)                 a new list with the elements of the row r
      l +:= x, l +:= r         append an element x or the elements of a row r; yields l
      UPB l, LWB l             the number of elements, 1
      SIZE l                   the number of elements (as for the maps of Hashmaps)
      i ELEM l                 the i-th element
      i AT l                   the name of the i-th element: i AT l := x, i AT l +:= 1
      POP l                    remove the last element and yield it
      CLEAR l                  remove all elements; yields l
      SORT l                   sort in ascending order (FALSE before TRUE); yields l
      l INDEX x                the index of the first element equal to x, or 0
      l HAS x                  whether an element is equal to x
      l REMOVE i               remove the i-th element and yield it (the elements after it move down)
      TOROW l                  the elements as a row [1 : UPB l] (a copy)

  For a Stringlist, +:=, INDEX and HAS also take a char ("x" is a char,
  and an operand is not rowed to a string).

  The operators work for all the modes; AT, INDEX, HAS and REMOVE have
  priority 7.  The module Hashmaps makes this module public (access pub
  Lists): a program that uses both accesses only Hashmaps.

  Example:

      access Lists (
          Intlist l = new_intlist;
          for i to 100000 do l +:= i * i od;
          5 AT l +:= 1;
          puts (whole (UPB l, 0) + " " + whole (5 ELEM l, 0) + "'n")
      )

  Bundled with a68j-backend.jar; a program needs -fnest-java only to
  declare formal holes of its own, not to access this module. }

module Lists =
def
    {{ The priorities of the dyadic operators of Lists and Hashmaps: a program
       can access only one module that declares the priority of an operator,
       so Hashmaps declares none and makes these public with access pub Lists. }}
    pub prio AT = 7, INDEX = 7, HAS = 7, REMOVE = 7;

'''

ALGOL_KIND = '''    {{ {mode}: a list of {amode} (a68j.jlib.{cls}). }}

    pub mode {mode} = ref {mode}_object;
    pub mode {mode}_object = struct (int {lower}_java_object);

    proc {mode} {p}_create = nest Java "a68j.jlib.{cls}.create";
    proc (int) {mode} {p}_with_capacity = nest Java "a68j.jlib.{cls}.withCapacity";
    proc ([] {amode}) {mode} {p}_of_array = nest Java "a68j.jlib.{cls}.ofArray";
    proc ({mode}, {amode}) void {p}_add = nest Java "a68j.jlib.{cls}.add";
    proc ({mode}) int {p}_size = nest Java "a68j.jlib.{cls}.size";
    proc ({mode}, int) {amode} {p}_get = nest Java "a68j.jlib.{cls}.get";
    proc ({mode}, int) ref {amode} {p}_at = nest Java "a68j.jlib.{cls}.at";
    proc ({mode}) {amode} {p}_remove_last = nest Java "a68j.jlib.{cls}.removeLast";
    proc ({mode}, int) {amode} {p}_remove_at = nest Java "a68j.jlib.{cls}.removeAt";
    proc ({mode}) void {p}_clear = nest Java "a68j.jlib.{cls}.clear";
    proc ({mode}) [] {amode} {p}_to_array = nest Java "a68j.jlib.{cls}.toArray";
    proc ({mode}) void {p}_sort = nest Java "a68j.jlib.{cls}.sort";
    proc ({mode}, {amode}) int {p}_index_of = nest Java "a68j.jlib.{cls}.indexOf";

    pub proc new_{lower} = {mode}: {p}_create;
    pub proc new_{lower}_with_capacity = (int capacity) {mode}: {p}_with_capacity (capacity);
    pub proc {lower}_of = ([] {amode} r) {mode}: {p}_of_array (r);
    pub op +:= = ({mode} l, {amode} x) {mode}: ({p}_add (l, x); l);
    pub op +:= = ({mode} l, [] {amode} r) {mode}: (for i from LWB r to UPB r do {p}_add (l, r[i]) od; l);
    pub op UPB = ({mode} l) int: {p}_size (l);
    pub op LWB = ({mode} l) int: 1;
    pub op SIZE = ({mode} l) int: {p}_size (l);
    pub op ELEM = (int i, {mode} l) {amode}: {p}_get (l, i);
    pub op AT = (int i, {mode} l) ref {amode}: {p}_at (l, i);
    pub op POP = ({mode} l) {amode}: {p}_remove_last (l);
    pub op CLEAR = ({mode} l) {mode}: ({p}_clear (l); l);
    pub op SORT = ({mode} l) {mode}: ({p}_sort (l); l);
    pub op INDEX = ({mode} l, {amode} x) int: {p}_index_of (l, x);
    pub op HAS = ({mode} l, {amode} x) bool: {p}_index_of (l, x) > 0;
    pub op REMOVE = ({mode} l, int i) {amode}: {p}_remove_at (l, i);
    pub op TOROW = ({mode} l) [] {amode}: {p}_to_array (l);
{char_ops}
'''


# A one-character denotation "x" is a CHAR, and an operand is not rowed to a
# STRING (rowing is strong, an operand firm): a Stringlist also takes a CHAR.
CHAR_OPS = '''    pub op +:= = ({mode} l, char x) {mode}: ({p}_add (l, x); l);
    pub op INDEX = ({mode} l, char x) int: {p}_index_of (l, x);
    pub op HAS = ({mode} l, char x) bool: {p}_index_of (l, x) > 0;
'''


def main():
    out = [ALGOL_HEAD]
    for mode, amode, cls, elem, rowtype, desc in KINDS:
        lower = mode.lower()
        char_ops = CHAR_OPS.format(mode=mode, p="j_" + lower) if amode == "string" else ""
        out.append(ALGOL_KIND.format(mode=mode, amode=amode, cls=cls, lower=lower, p="j_" + lower, char_ops=char_ops))
        path = os.path.join(ROOT, "backend/src/main/java/a68j/jlib", cls + ".java")
        with open(path, "w") as f:
            f.write(java_class(mode, amode, cls, elem, rowtype, desc))
    out.append("    skip\nfed\n")
    with open(os.path.join(ROOT, "backend/lib/lists.a68"), "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
