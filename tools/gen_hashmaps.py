#!/usr/bin/env python3
"""Generate the module Hashmaps of a68j from one template:

  backend/lib/hashmaps.a68                       the Algol 68 module (modes Int_int_map, ...)
  backend/src/main/java/a68j/jlib/XYMap.java     one Java class per key and value mode

Usage: tools/gen_hashmaps.py   (run from anywhere; overwrites the files)

Every map is a hash table with open addressing (linear probing) over an
index table of 2^k ints, and keeps its entries in insertion order in
parallel arrays of the key and value types, unboxed (the layout of the
"compact dict" of CPython). Looking up, inserting and removing take
expected constant time; KEYS and VALUES give the entries in the order
they were inserted, so a program prints the same on every run.
"""
