def main():
    out = [ALGOL_HEAD]
    for kname, kalg, kcls, kparam, kstored in KEYS:
        for vname, valg, vcls, vtype, vbox, vdefault in VALUES:
            mode = kname + "_" + vname.lower() + "_map"
            cls = kcls + vcls + "Map"
            lower = mode.lower()
            char_ops = CHAR_OPS.format(mode=mode, valg=valg, p="j_" + lower) if kalg == "string" else ""
            out.append(ALGOL_KIND.format(mode=mode, kalg=kalg, valg=valg, cls=cls, lower=lower, p="j_" + lower, char_ops=char_ops))
            path = os.path.join(ROOT, "backend/src/main/java/a68j/jlib", cls + ".java")
            with open(path, "w") as f:
                f.write(java_class(mode, cls, kalg, kparam, kstored, valg, vtype, vbox, vdefault))
    out.append("    skip\nfed\n")
    with open(os.path.join(ROOT, "backend/lib/hashmaps.a68"), "w") as f:
        f.write("".join(out))


