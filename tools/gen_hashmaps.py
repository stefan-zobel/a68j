def java_class(mode, cls, kalg, kparam, kstored, valg, vtype, vbox, vdefault):
    s = {}
    s["mode"], s["cls"], s["kparam"], s["kstored"], s["vtype"] = mode, cls, kparam, kstored, vtype
    s["kdesc"], s["vdesc"] = kalg.upper(), valg.upper()
