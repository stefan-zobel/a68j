    if kparam == "int":
        s["hash"] = "        int h = k * 0x9E3779B9;\n        return h ^ (h >>> 16);"
        s["equal"] = "keys[e] == k"
        s["show"] = "Integer.toString(k)"
        s["kstore_k"] = "k"
        s["kname"] = "k"
        s["krow"] = "int[]"
