def prefixed(rules, prefix):
    """The rules with their names, and the includes among them, prefixed."""
    def walk(node):
        if isinstance(node, dict):
            out = {}
            for k, v in node.items():
                if k == "include" and v.startswith("#") and v[1:] in rules:
                    out[k] = "#" + prefix + v[1:]
                else:
                    out[k] = walk(v)
            return out
        if isinstance(node, list):
            return [walk(v) for v in node]
        return node
    return {prefix + k: walk(v) for k, v in rules.items()}


