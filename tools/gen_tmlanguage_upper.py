def u_names(ws, prefixed):
    """max int -> max[ \\t_]*int; not when the name goes on (max intx)."""
    ws = sorted(set(ws), key=lambda w: (-len(w), w))
    alts = "|".join(re.sub(r"[ _]", lambda m: U_SEP, w) for w in ws)
    pre = r"(?:(?:long|short)" + U_SEP + ")*" if prefixed else ""
    return U_T + pre + "(?:" + alts + r")(?![a-z0-9_]|[ \t]*[a-z0-9])"


