"""Generates the TextMate grammar for Algol 68 in UPPER and SUPPER stropping.

Output: editors/textmate-algol68/syntaxes/algol68.tmLanguage.json, a grammar
of its own. It covers the Revised Report, Algol 68 Genie (a68g-keywords.c,
prelude.c; version 3.5.9) and ga68 in UPPER stropping, and ga68 in SUPPER
stropping. Quote stropping ('BEGIN') is not covered.

The rules for SUPPER are those of the SUPPER grammar, read from
editors/vscode-algol68/syntaxes/algol68.tmLanguage.json (generated by
tools/gen_tmlanguage.py, which this script neither runs nor changes).

The two regimes contradict each other: in UPPER, in, out, file, real and
to are ordinary identifiers, in SUPPER they are reserved; #, CO, COMMENT,
PR and PRAGMAT exist only in UPPER. A TextMate grammar sees one line at a
time and cannot look at the whole file first. So the first word that tells
the regimes apart decides the rest of the file: a reserved word in capitals
(BEGIN, PROC, INT, PR, CO) or a # opens a region for UPPER, a reserved word
in lower case (begin, proc, int) or [[ one for SUPPER. Neither region ever
ends (the end pattern (?!) never matches). Before that word, a neutral set
of rules colors comments in braces, strings, numbers and names.

Rules of UPPER (Scanner.java for ga68, parser-scanner.c for Genie):

* Reserved words and bold words (modes, operators) consist of capitals and
  underscores; digits do not belong to them.
* Identifiers consist of lower case letters, digits and underscores, and
  may contain blanks: "max int" is the identifier maxint. The rule for
  identifiers takes all the words of a name, and the names of the prelude
  allow a blank or an underscore between their parts.
* Comments: # ... #, CO ... CO, COMMENT ... COMMENT, NOTE ... ETON (GNU,
  nestable) and { ... } (GNU). A comment ends at the first occurrence of its
  closing delimiter, also inside a word, as in the scanners. In Genie { }
  are brackets; the grammar follows ga68 here.
* Pragmats: PR ... PR, PRAGMAT ... PRAGMAT, ORDER ... REDRO (GNU).
* Strings: "" is a quote. Genie knows no escapes, and the GNU escapes 'n
  and 't would color "don't" wrongly, so only '(u00e4) is colored.
* Bits denotations may contain blanks after 16r as well.
* Mode or operator? Both are written in capitals. A bold word right after
  an operand (an identifier, a number or a string) is a dyadic operator
  (a MAX b), any other one a mode, except after MODE, OP and PRIO.

Usage: python3 tools/gen_tmlanguage_upper.py
"""

