#!/usr/bin/env python3
"""Generate the module Bigints of a68j:

  backend/lib/bigints.a68   the Algol 68 module (mode Bigint, its operators
                            and procedures)

Usage: tools/gen_bignums.py   (run from anywhere; overwrites the file)

The Java side, backend/src/main/java/a68j/jlib/BigInt.java, is written by
hand.  This script writes the many operator declarations that give a Bigint
the operators of an int, with the same priorities and the same meaning
(docs/bigints.md): every dyadic operator for two Bigints and for a Bigint
with an int, long int or long long int on either side, and every assigning
operator for a Bigint variable.

The tables below describe one kind of number.  A later kind, such as a
decimal mode on java.math.BigDecimal in a module of its own that accesses
Bigints publicly, would add an entry with its own Java class, mixed operand
modes and operators.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The operand modes that mix with a Bigint, and the part of the names of the
# formal holes for them.  Each is passed to a Java long.
MIXED = [("int", "int"), ("long int", "long_int"), ("long long int", "long_long_int")]

# Dyadic operators with a Bigint result: symbol, Java method.
ARITH = [("+", "add"), ("-", "subtract"), ("*", "multiply"),
         ("%", "divide"), ("OVER", "divide"), ("MOD", "mod"), ("%*", "mod")]

# Comparisons: symbol, the test of the result of compare (-1, 0 or 1).
COMPARE = [("=", "= 0"), ("/=", "/= 0"), ("<", "< 0"), ("<=", "<= 0"),
           (">", "> 0"), (">=", ">= 0"),
           ("EQ", "= 0"), ("NE", "/= 0"), ("LT", "< 0"), ("LE", "<= 0"),
           ("GT", "> 0"), ("GE", ">= 0")]

# Assigning operators: symbol, Java method of the operation.
ASSIGN = [("+:=", "add"), ("-:=", "subtract"), ("*:=", "multiply"),
          ("%:=", "divide"), ("%*:=", "mod"),
          ("PLUSAB", "add"), ("MINUSAB", "subtract"), ("TIMESAB", "multiply"),
          ("OVERAB", "divide"), ("MODAB", "mod")]

# The power: symbols, all with an int exponent.
POWER = ["**", "UP", "^"]

# The Java methods with a second operand, in the three forms of BigInt.java.
DYADIC_JAVA = ["add", "subtract", "multiply", "divide", "mod", "compare"]

HEAD = '''{ dg-options "-fstropping=supper -fnest-java" }

{ Copyright (C) 2026 The a68j authors
  SPDX-License-Identifier: GPL-3.0-or-later WITH GCC-exception-3.1

  This file is part of a68j. It is licensed under the GNU General Public
  License, version 3 or later. Under Section 7 of GPL version 3, you are
  granted additional permissions described in the GCC Runtime Library
  Exception, version 3.1, as published by the Free Software Foundation; see
  the files COPYING and COPYING.RUNTIME.

  Additional permission under GNU GPL version 3 section 7: for this file, a
  Compilation Process done with a68j, alone or with other GPL-compatible
  software, is an Eligible Compilation Process in the sense of the GCC
  Runtime Library Exception, version 3.1. }

{ bigints.a68 - the module Bigints of a68j.  Generated by
  tools/gen_bignums.py; do not edit.

  Integers of any size, mode Bigint, with the operators of an int.  The
  values are java.math.BigInteger objects (a68j.jlib.BigInt), which never
  change: an operator yields a new Bigint.

  A Bigint is a Java object: a name that refers to no Algol 68 value.  It
  can be passed around, kept in variables (Bigint x := BIG 1) and given to
  the operators and procedures below, but not dereferenced or assigned to.
  IS compares the objects, = compares the values.  For Bigints a and b and
  a value n of mode int, long int or long long int:

      BIG n, BIG s             the Bigint of n, or of the decimal digits in
                               the string s (white space around them, a
                               sign + or - directly before them)
      TOINT a, TOLONGINT a     a as an int or long int; a value beyond the
                               limits is a runtime error
      big_whole (a, width)     a as a string, with the rules of whole
      big_text (a, radix), big_from_text (s, radix)
                               a in the radix 2 to 36, and back
      - a, + a, ABS a          negation, a itself, the absolute value
      SIGN a, ODD a            -1, 0 or 1; whether a is odd
      a + b, a - b, a * b      for a Bigint and a Bigint, int, long int or
      a % b, a OVER b          long long int on either side; % and OVER
      a MOD b, a %* b          truncate toward zero, MOD yields a value
                               from 0 to ABS b - 1
      a = b, a /= b, a < b, a <= b, a > b, a >= b, EQ, NE, LT, LE, GT, GE
                               the same operand modes
      a ** e, a UP e, a ^ e    the power with an int exponent e >= 0
      x +:= b, x -:= b, x *:= b, x %:= b, x %*:= b, PLUSAB, MINUSAB,
      TIMESAB, OVERAB, MODAB   for a variable x of mode ref Bigint and b a
                               Bigint, int, long int or long long int
      big_gcd (a, b)           the greatest common divisor
      big_sqrt (a)             the largest integer whose square is at most a
      big_mod_pow (a, e, m)    a ** e MOD m, for e >= 0 and m > 0
      big_probable_prime (a)   whether a is a prime, with an error
                               probability below 2 ** -100

  The operators have the priorities of the prelude; the module declares
  none, so a program can access it together with Lists, Hashmaps, Texts
  and Genie_Transput.  A NIL Bigint, a division by zero, a negative
  exponent and a value beyond the limits of TOINT are runtime errors.

  Example:

      access Bigints (
          Bigint f := BIG 1;
          for i to 30 do f *:= i od;
          puts (big_whole (f, 0) + "'n")
      )

  Bundled with a68j-backend.jar; a program needs -fnest-java only to
  declare formal holes of its own, not to access this module. }

module Bigints =
def
    pub mode Bigint = ref Bigint_object;
    pub mode Bigint_object = struct (int bigint_java_object);

'''

J = "a68j.jlib.BigInt"


def hole(mode, name, method):
    return '    proc %s j_%s = nest Java "%s.%s";\n' % (mode, name, J, method)


def holes():
    out = []
    for m, s in MIXED:
        out.append(hole("(%s) Bigint" % m, "of_" + s, "of"))
    out.append(hole("(string) Bigint", "parse", "parse"))
    out.append(hole("(string, int) Bigint", "parse_radix", "parseRadix"))
    out.append(hole("(Bigint) int", "to_int", "toInt"))
    out.append(hole("(Bigint) long int", "to_long_int", "toLong"))
    out.append(hole("(Bigint, int) string", "whole", "whole"))
    out.append(hole("(Bigint, int) string", "text", "text"))
    out.append(hole("(Bigint) Bigint", "negate", "negate"))
    out.append(hole("(Bigint) Bigint", "abs", "abs"))
    out.append(hole("(Bigint) int", "sign", "sign"))
    out.append(hole("(Bigint) bool", "odd", "odd"))
    out.append(hole("(Bigint, int) Bigint", "pow", "pow"))
    out.append(hole("(Bigint, Bigint) Bigint", "gcd", "gcd"))
    out.append(hole("(Bigint) Bigint", "sqrt", "sqrt"))
    out.append(hole("(Bigint, Bigint, Bigint) Bigint", "mod_pow", "modPow"))
    out.append(hole("(Bigint) bool", "probable_prime", "probablePrime"))
    for j in DYADIC_JAVA:
        r = "int" if j == "compare" else "Bigint"
        out.append(hole("(Bigint, Bigint) %s" % r, j, j))
        for m, s in MIXED:
            out.append(hole("(Bigint, %s) %s" % (m, r), "%s_%s" % (j, s), j))
            out.append(hole("(%s, Bigint) %s" % (m, r), "%s_%s" % (s, j), j))
    return "".join(out)


def operators():
    out = ["\n    { Conversions and output. }\n\n"]
    for m, s in MIXED:
        out.append("    pub op BIG = (%s n) Bigint: j_of_%s (n);\n" % (m, s))
    out.append("    pub op BIG = (string s) Bigint: j_parse (s);\n")
    # A one-character denotation "7" is a char, and an operand is not rowed
    # to a string.
    out.append("    pub op BIG = (char c) Bigint: j_parse (c);\n")
    out.append("    pub op TOINT = (Bigint a) int: j_to_int (a);\n")
    out.append("    pub op TOLONGINT = (Bigint a) long int: j_to_long_int (a);\n")
    out.append("    pub proc big_whole = (Bigint a, int width) string: j_whole (a, width);\n")
    out.append("    pub proc big_text = (Bigint a, int radix) string: j_text (a, radix);\n")
    out.append("    pub proc big_from_text = (string s, int radix) Bigint: j_parse_radix (s, radix);\n")

    out.append("\n    { Monadic operators. }\n\n")
    out.append("    pub op - = (Bigint a) Bigint: j_negate (a);\n")
    out.append("    pub op + = (Bigint a) Bigint: a;\n")
    out.append("    pub op ABS = (Bigint a) Bigint: j_abs (a);\n")
    out.append("    pub op SIGN = (Bigint a) int: j_sign (a);\n")
    out.append("    pub op ODD = (Bigint a) bool: j_odd (a);\n")

    out.append("\n    { Dyadic operators: two Bigints, or a Bigint and an int, long int or\n"
               "      long long int on either side. }\n\n")
    for op, j in ARITH:
        out.append("    pub op %s = (Bigint a, b) Bigint: j_%s (a, b);\n" % (op, j))
        for m, s in MIXED:
            out.append("    pub op %s = (Bigint a, %s b) Bigint: j_%s_%s (a, b);\n" % (op, m, j, s))
            out.append("    pub op %s = (%s a, Bigint b) Bigint: j_%s_%s (a, b);\n" % (op, m, s, j))
    for op in POWER:
        out.append("    pub op %s = (Bigint a, int e) Bigint: j_pow (a, e);\n" % op)

    out.append("\n    { Comparisons. }\n\n")
    for op, test in COMPARE:
        out.append("    pub op %s = (Bigint a, b) bool: j_compare (a, b) %s;\n" % (op, test))
        for m, s in MIXED:
            out.append("    pub op %s = (Bigint a, %s b) bool: j_compare_%s (a, b) %s;\n" % (op, m, s, test))
            out.append("    pub op %s = (%s a, Bigint b) bool: j_%s_compare (a, b) %s;\n" % (op, m, s, test))

    out.append("\n    { Assigning operators: they yield the variable. }\n\n")
    for op, j in ASSIGN:
        out.append("    pub op %s = (ref Bigint x, Bigint b) ref Bigint: x := j_%s (x, b);\n" % (op, j))
        for m, s in MIXED:
            out.append("    pub op %s = (ref Bigint x, %s b) ref Bigint: x := j_%s_%s (x, b);\n" % (op, m, j, s))

    out.append("\n    { Procedures. }\n\n")
    out.append("    pub proc big_gcd = (Bigint a, b) Bigint: j_gcd (a, b);\n")
    out.append("    pub proc big_sqrt = (Bigint a) Bigint: j_sqrt (a);\n")
    out.append("    pub proc big_mod_pow = (Bigint a, e, m) Bigint: j_mod_pow (a, e, m);\n")
    out.append("    pub proc big_probable_prime = (Bigint a) bool: j_probable_prime (a);\n")
    return "".join(out)


def main():
    text = HEAD + holes() + operators() + "\n    skip\nfed\n"
    with open(os.path.join(ROOT, "backend/lib/bigints.a68"), "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
