#!/usr/bin/env python3
"""Generate the modules Bigints and Bigdecimals of a68j:

  backend/lib/bigints.a68       the Algol 68 module Bigints (mode Bigint,
                                its operators and procedures)
  backend/lib/bigdecimals.a68   the Algol 68 module Bigdecimals (mode
                                Bigdecimal, which accesses Bigints publicly)

Usage: tools/gen_bignums.py   (run from anywhere; overwrites the files)

The Java side, backend/src/main/java/a68j/jlib/BigInt.java and BigDec.java,
is written by hand.  This script writes the many operator declarations that
give a Bigint the operators of an int and a Bigdecimal those of a real, with
the same priorities and the same meaning (docs/bigints.md,
docs/bigdecimals.md): every dyadic operator for two values of the mode and
for one with a value of another mode on either side, and every assigning
operator for a variable of the mode.

A Bigint operator with an int calls a Java method with a long parameter.  A
Bigdecimal operator with another mode first converts that operand exactly
(the Java methods exact...) and then calls the method for two Bigdecimals,
which rounds the result once.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The operand modes that mix with a Bigint, and the part of the names of the
# formal holes for them.  Each is passed to a Java long.
MIXED = [("int", "int"), ("long int", "long_int"), ("long long int", "long_long_int")]

# Dyadic operators with a Bigint result: symbol, Java method.
ARITH = [("+", "add"), ("-", "subtract"), ("*", "multiply"),
         ("%", "divide"), ("OVER", "divide"), ("MOD", "mod"), ("%*", "mod")]

# Comparisons: symbol, the test of the result of compare (-1, 0 or 1).
COMPARE = [("=", "= 0"), ("/=", "/= 0"), ("<", "< 0"), ("<=", "<= 0"),
           (">", "> 0"), (">=", ">= 0"),
           ("EQ", "= 0"), ("NE", "/= 0"), ("LT", "< 0"), ("LE", "<= 0"),
           ("GT", "> 0"), ("GE", ">= 0")]

# Assigning operators: symbol, Java method of the operation.
ASSIGN = [("+:=", "add"), ("-:=", "subtract"), ("*:=", "multiply"),
          ("%:=", "divide"), ("%*:=", "mod"),
          ("PLUSAB", "add"), ("MINUSAB", "subtract"), ("TIMESAB", "multiply"),
          ("OVERAB", "divide"), ("MODAB", "mod")]

# The power: symbols, all with an int exponent.
POWER = ["**", "UP", "^"]

# The Java methods with a second operand, in the three forms of BigInt.java.
DYADIC_JAVA = ["add", "subtract", "multiply", "divide", "mod", "compare"]

