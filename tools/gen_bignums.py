# The operand modes that mix with a Bigdecimal: mode, the part of the names
# of the formal holes, the Java method of DEC (which rounds) and the one of
# the exact conversion for the mixed operators.
DEC_MIXED = [("int", "int", "ofLong", "exactLong"),
             ("long int", "long_int", "ofLong", "exactLong"),
             ("long long int", "long_long_int", "ofLong", "exactLong"),
             ("real", "real", "ofFloat", "exactFloat"),
             ("long real", "long_real", "ofDouble", "exactDouble"),
             ("long long real", "long_long_real", "ofDouble", "exactDouble"),
             ("Bigint", "bigint", "ofBigint", "exactBigint")]

# The integer modes that a Bigint / divides, through BIG of Bigints.
DEC_BIGINT_MIXED = ["int", "long int", "long long int"]

# Dyadic operators with a Bigdecimal result: symbol, Java method.
DEC_ARITH = [("+", "add"), ("-", "subtract"), ("*", "multiply"), ("/", "divide")]

# Assigning operators: symbol, Java method of the operation.
DEC_ASSIGN = [("+:=", "add"), ("-:=", "subtract"), ("*:=", "multiply"),
              ("/:=", "divide"),
              ("PLUSAB", "add"), ("MINUSAB", "subtract"), ("TIMESAB", "multiply"),
              ("DIVAB", "divide")]

DEC_HEAD = HEAD.split("{ bigints.a68")[0] + '''{ bigdecimals.a68 - the module Bigdecimals of a68j.  Generated by
  tools/gen_bignums.py; do not edit.

  Decimals of any precision, mode Bigdecimal, with the operators of a
  real.  The values are java.math.BigDecimal objects (a68j.jlib.BigDec),
  which never change: an operator yields a new Bigdecimal.  The module
  accesses Bigints publicly, so a program that accesses Bigdecimals can use
  the Bigints as well.

  Every operation rounds its result to the precision, a number of
  significant decimal digits: 70 at the start, as the long long real of
  Algol 68 Genie.  The precision can be changed at any time; the values
  already computed keep their digits.  Rounding is half away from zero.

  A Bigdecimal is a Java object: a name that refers to no Algol 68 value.
  It can be passed around, kept in variables (Bigdecimal x := DEC 1) and
  given to the operators and procedures below, but not dereferenced or
  assigned to.  IS compares the objects, = compares the values (DEC "1.0"
  = DEC "1.00").  For Bigdecimals a and b, a value n of mode int, long int,
  long long int, real, long real, long long real or Bigint, and Bigints i
  and j:

      DEC n, DEC s             the Bigdecimal of n, or of the decimal
                               number in the string s (a sign, digits with
                               or without a point, an exponent with e or E;
                               white space around it), rounded; a real
                               gives its shortest decimal (DEC 0.1 is 0.1)
      TOREAL a, TOLONGREAL a   a as a real or long real; a value beyond the
                               limits is a runtime error
      ROUND a, ENTIER a        the nearest Bigint (half away from zero), the
                               largest Bigint not greater than a
      - a, + a, ABS a          negation, a rounded to the precision, the
                               absolute value
      SIGN a                   -1, 0 or 1
      a + b, a - b, a * b, a / b
                               for a Bigdecimal and a Bigdecimal or n on
                               either side
      i / j                    the quotient as a Bigdecimal, also for i or
                               j an int, long int or long long int
      a = b, a /= b, a < b, a <= b, a > b, a >= b, EQ, NE, LT, LE, GT, GE
                               the same operand modes as a + b
      a ** e, a UP e, a ^ e    the power with an int exponent e, also
                               negative
      x +:= b, x -:= b, x *:= b, x /:= b, PLUSAB, MINUSAB, TIMESAB, DIVAB
                               for a variable x of mode ref Bigdecimal and b
                               a Bigdecimal or n
      bigdec_set_precision (d), bigdec_precision
                               set the precision to d >= 1 digits, and the
                               precision
      bigdec_sqrt (a)          the square root, for a >= 0
      bigdec_whole (a, width), bigdec_fixed (a, width, after),
      bigdec_float (a, width, after, exp)
                               a as a string, with the rules of whole, fixed
                               and float
      bigdec_text (a)          a as a string without exponent and without
                               trailing zeros

  The operators have the priorities of the prelude; the module declares
  none, so a program can access it together with Lists, Hashmaps, Texts
  and Genie_Transput.  A NIL Bigdecimal, a division by zero, a negative
  argument of bigdec_sqrt, a precision below 1 and a text that is not a
  number are runtime errors.

  Example:

      access Bigdecimals (
          bigdec_set_precision (50);
          puts (bigdec_text (bigdec_sqrt (DEC 2)) + "'n")
      )

  Bundled with a68j-backend.jar; a program needs -fnest-java only to
  declare formal holes of its own, not to access this module. }

module Bigdecimals =
access pub Bigints
def
    pub mode Bigdecimal = ref Bigdecimal_object;
    pub mode Bigdecimal_object = struct (int bigdecimal_java_object);

'''

JD = "a68j.jlib.BigDec"


def dec_hole(mode, name, method):
    return '    proc %s j_%s = nest Java "%s.%s";\n' % (mode, name, JD, method)


def dec_holes():
    out = []
    for m, s, of, exact in DEC_MIXED:
        out.append(dec_hole("(%s) Bigdecimal" % m, "of_" + s, of))
    for m, s, of, exact in DEC_MIXED:
        out.append(dec_hole("(%s) Bigdecimal" % m, "exact_" + s, exact))
    out.append(dec_hole("(string) Bigdecimal", "parse", "parse"))
    out.append(dec_hole("(Bigdecimal) real", "to_real", "toFloat"))
    out.append(dec_hole("(Bigdecimal) long real", "to_long_real", "toDouble"))
    out.append(dec_hole("(Bigdecimal) Bigint", "round", "round"))
    out.append(dec_hole("(Bigdecimal) Bigint", "entier", "entier"))
    out.append(dec_hole("(Bigdecimal) Bigdecimal", "plus", "plus"))
    out.append(dec_hole("(Bigdecimal) Bigdecimal", "negate", "negate"))
    out.append(dec_hole("(Bigdecimal) Bigdecimal", "abs", "abs"))
    out.append(dec_hole("(Bigdecimal) int", "sign", "sign"))
    for op, j in DEC_ARITH:
        out.append(dec_hole("(Bigdecimal, Bigdecimal) Bigdecimal", j, j))
    out.append(dec_hole("(Bigint, Bigint) Bigdecimal", "divide_bigints", "divideBigints"))
    out.append(dec_hole("(Bigdecimal, Bigdecimal) int", "compare", "compare"))
    out.append(dec_hole("(Bigdecimal, int) Bigdecimal", "pow", "pow"))
    out.append(dec_hole("(int) void", "set_precision", "setPrecision"))
    out.append(dec_hole("int", "precision", "precision"))
    out.append(dec_hole("(Bigdecimal) Bigdecimal", "sqrt", "sqrt"))
    out.append(dec_hole("(Bigdecimal, int) string", "whole", "whole"))
    out.append(dec_hole("(Bigdecimal, int, int) string", "fixed", "fixed"))
    out.append(dec_hole("(Bigdecimal, int, int, int) string", "float", "floating"))
    out.append(dec_hole("(Bigdecimal) string", "text", "text"))
    return "".join(out)


def dec_operators():
    out = ["\n    { Conversions. }\n\n"]
    for m, s, of, exact in DEC_MIXED:
        out.append("    pub op DEC = (%s n) Bigdecimal: j_of_%s (n);\n" % (m, s))
    out.append("    pub op DEC = (string s) Bigdecimal: j_parse (s);\n")
    # A one-character denotation "7" is a char, and an operand is not rowed
    # to a string.
    out.append("    pub op DEC = (char c) Bigdecimal: j_parse (c);\n")
    out.append("    pub op TOREAL = (Bigdecimal a) real: j_to_real (a);\n")
    out.append("    pub op TOLONGREAL = (Bigdecimal a) long real: j_to_long_real (a);\n")
    out.append("    pub op ROUND = (Bigdecimal a) Bigint: j_round (a);\n")
    out.append("    pub op ENTIER = (Bigdecimal a) Bigint: j_entier (a);\n")

    out.append("\n    { Monadic operators. }\n\n")
    out.append("    pub op - = (Bigdecimal a) Bigdecimal: j_negate (a);\n")
    out.append("    pub op + = (Bigdecimal a) Bigdecimal: j_plus (a);\n")
    out.append("    pub op ABS = (Bigdecimal a) Bigdecimal: j_abs (a);\n")
    out.append("    pub op SIGN = (Bigdecimal a) int: j_sign (a);\n")

    out.append("\n    { Dyadic operators: two Bigdecimals, or a Bigdecimal and an int, long\n"
               "      int, long long int, real, long real, long long real or Bigint on\n"
               "      either side. }\n\n")
    for op, j in DEC_ARITH:
        out.append("    pub op %s = (Bigdecimal a, b) Bigdecimal: j_%s (a, b);\n" % (op, j))
        for m, s, of, exact in DEC_MIXED:
            out.append("    pub op %s = (Bigdecimal a, %s b) Bigdecimal: j_%s (a, j_exact_%s (b));\n" % (op, m, j, s))
            out.append("    pub op %s = (%s a, Bigdecimal b) Bigdecimal: j_%s (j_exact_%s (a), b);\n" % (op, m, j, s))
    for op in POWER:
        out.append("    pub op %s = (Bigdecimal a, int e) Bigdecimal: j_pow (a, e);\n" % op)

    out.append("\n    { The quotient of two Bigints, or of a Bigint and an int, long int or\n"
               "      long long int on either side. }\n\n")
    out.append("    pub op / = (Bigint a, b) Bigdecimal: j_divide_bigints (a, b);\n")
    for m in DEC_BIGINT_MIXED:
        out.append("    pub op / = (Bigint a, %s b) Bigdecimal: j_divide_bigints (a, BIG b);\n" % m)
        out.append("    pub op / = (%s a, Bigint b) Bigdecimal: j_divide_bigints (BIG a, b);\n" % m)

    out.append("\n    { Comparisons. }\n\n")
    for op, test in COMPARE:
        out.append("    pub op %s = (Bigdecimal a, b) bool: j_compare (a, b) %s;\n" % (op, test))
        for m, s, of, exact in DEC_MIXED:
            out.append("    pub op %s = (Bigdecimal a, %s b) bool: j_compare (a, j_exact_%s (b)) %s;\n" % (op, m, s, test))
            out.append("    pub op %s = (%s a, Bigdecimal b) bool: j_compare (j_exact_%s (a), b) %s;\n" % (op, m, s, test))

    out.append("\n    { Assigning operators: they yield the variable. }\n\n")
    for op, j in DEC_ASSIGN:
        out.append("    pub op %s = (ref Bigdecimal x, Bigdecimal b) ref Bigdecimal: x := j_%s (x, b);\n" % (op, j))
        for m, s, of, exact in DEC_MIXED:
            out.append("    pub op %s = (ref Bigdecimal x, %s b) ref Bigdecimal: x := j_%s (x, j_exact_%s (b));\n" % (op, m, j, s))

    out.append("\n    { Procedures. }\n\n")
    out.append("    pub proc bigdec_set_precision = (int digits) void: j_set_precision (digits);\n")
    out.append("    pub proc bigdec_precision = int: j_precision;\n")
    out.append("    pub proc bigdec_sqrt = (Bigdecimal a) Bigdecimal: j_sqrt (a);\n")
    out.append("    pub proc bigdec_whole = (Bigdecimal a, int width) string: j_whole (a, width);\n")
    out.append("    pub proc bigdec_fixed = (Bigdecimal a, int width, after) string: j_fixed (a, width, after);\n")
    out.append("    pub proc bigdec_float = (Bigdecimal a, int width, after, exp) string: j_float (a, width, after, exp);\n")
    out.append("    pub proc bigdec_text = (Bigdecimal a) string: j_text (a);\n")
    return "".join(out)


def main():
    text = HEAD + holes() + operators() + "\n    skip\nfed\n"
    with open(os.path.join(ROOT, "backend/lib/bigints.a68"), "w", newline="\n") as f:
        f.write(text)
    text = DEC_HEAD + dec_holes() + dec_operators() + "\n    skip\nfed\n"
    with open(os.path.join(ROOT, "backend/lib/bigdecimals.a68"), "w", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
